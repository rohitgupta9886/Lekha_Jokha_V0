  getSettings() {
    try {
      const stored = localStorage.getItem('lekha_app_settings');
      if (stored) {
        const parsed = JSON.parse(stored);
        const defaults = this.getDefaultSettings();
        // Deep merge with defaults to ensure all keys exist
        for (const sec in defaults) {
          if (!parsed[sec]) parsed[sec] = defaults[sec];
          else parsed[sec] = { ...defaults[sec], ...parsed[sec] };
        }
        return parsed;
      }
    } catch (e) {
      console.warn('Error reading app settings:', e);
    }
    return this.getDefaultSettings();
  },

  saveSettings(newSettings) {
    try {
      localStorage.setItem('lekha_app_settings', JSON.stringify(newSettings));
      if (window.Store && window.Store.data) {
        window.Store.data.appSettings = newSettings;
      }
      return true;
    } catch (e) {
      console.error('Failed to save app settings:', e);
      return false;
    }
  },

